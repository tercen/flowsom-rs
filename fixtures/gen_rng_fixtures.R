out <- "/out/"
set.seed(1)
u <- runif(10)
set.seed(1)
s1 <- sample(1:3000, 25, replace = FALSE)
set.seed(42)
s2 <- sample(1:10)
set.seed(7)
s3 <- sample(1:100, 30, replace = FALSE)
set.seed(7)
u2 <- runif(3)
write.csv(data.frame(u = sprintf("%.17g", u)), paste0(out, "rng_runif_seed1.csv"), row.names = FALSE)
write.csv(data.frame(i = s1), paste0(out, "rng_sample_3000_25_seed1.csv"), row.names = FALSE)
write.csv(data.frame(i = s2), paste0(out, "rng_sample_10_seed42.csv"), row.names = FALSE)
write.csv(data.frame(i = s3), paste0(out, "rng_sample_100_30_seed7.csv"), row.names = FALSE)
write.csv(data.frame(u = sprintf("%.17g", u2)), paste0(out, "rng_runif_seed7.csv"), row.names = FALSE)
cat("R", as.character(getRversion()), "sample.kind:", RNGkind()[3], "\n")
cat("runif(1) seed1:", sprintf("%.17g", u[1]), "\n")
